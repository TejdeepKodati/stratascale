export function clonePortfolioWorkloads(
  workloads: Workload[],
  cycleTestEdges: Array<{ workloadId: string; addDependencyId: string }> = [],
  injectCycle = false
): Workload[] {
  const cloned = workloads.map((w) => ({
    ...w,
    dependencies: [...w.dependencies],
  }));

  if (!injectCycle || cycleTestEdges.length === 0) {
    return cloned;
  }

  const byId = new Map(cloned.map((w) => [w.id, w]));
  for (const edge of cycleTestEdges) {
    const target = byId.get(edge.workloadId);
    if (target && !target.dependencies.includes(edge.addDependencyId)) {
      target.dependencies.push(edge.addDependencyId);
    }
  }
  return cloned;
}
